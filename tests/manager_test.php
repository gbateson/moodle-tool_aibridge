#[\PHPUnit\Framework\Attributes\CoversClass(\tool_aibridge\logger::class)]
final class manager_test extends \advanced_testcase {
    /** A reply from an OpenAI-style chat API. */
    const CHAT_REPLY = '{"model": "gpt-test", "choices": [{"message": {"content": "Hello there"}}],
            "usage": {"prompt_tokens": 5, "completion_tokens": 2}}';

    /** @var \stdClass a user. */
    protected $user;

    /** @var \context_course a course context. */
    protected $context;

    /**
     * Set up a course with a student, and use only the bridge's providers.
     */
    protected function setUp(): void {
        parent::setUp();
        $this->resetAfterTest();
        set_config('coreroute', core_bridge::ROUTE_NEVER, 'tool_aibridge');
        set_config('requirepolicy', 0, 'tool_aibridge');
        $course = $this->getDataGenerator()->create_course();
        $this->user = $this->getDataGenerator()->create_and_enrol($course, 'student');
        $this->context = \context_course::instance($course->id);
    }

    /**
     * Get the generator.
     *
     * @return \tool_aibridge_generator
     */
    protected function get_generator(): \tool_aibridge_generator {
        return $this->getDataGenerator()->get_plugin_generator('tool_aibridge');
    }

    /**
     * Make a text action.
     *
     * @param string $prompt
     * @return generate_text
     */
    protected function text_action(string $prompt = 'Say hello'): generate_text {
        $action = new generate_text($this->context->id, $this->user->id, $prompt, 'Be brief.');
        $action->set_purpose('mod_test', 'greeting');
        return $action;
    }

    /**
     * Text is generated by a provider, and the request is logged.
     */
    public function test_generate_text(): void {
        global $DB;
        $provider = $this->get_generator()->create_provider(['name' => 'GPT']);
        \curl::mock_response(self::CHAT_REPLY);
        $response = manager::process($this->text_action());

        $this->assertTrue($response->get_success(), $response->get_error());
        $this->assertSame('Hello there', $response->get_content());
        $this->assertSame('gpt-test', $response->get_model());
        $this->assertSame($provider->get_id(), $response->get_providerid());
        $this->assertSame(response::ROUTE_EXTERNAL, $response->get_route());
        $this->assertSame('Made by AI (GPT)', $response->get_label());

        $log = $DB->get_record(logger::TABLE, ['id' => $response->get_logid()], '*', MUST_EXIST);
        $this->assertEquals($this->user->id, $log->userid);
        $this->assertEquals($this->context->id, $log->contextid);
        $this->assertSame('mod_test', $log->component);
        $this->assertSame('greeting', $log->purpose);
        $this->assertSame('generate_text', $log->action);
        $this->assertEquals(1, $log->success);
        $this->assertEquals(5, $log->prompttokens);
        $this->assertEquals(2, $log->completiontokens);
        // Prompts and replies are not kept by default.
        $this->assertNull($log->prompt);
        $this->assertNull($log->response);
    }

    /**
     * Prompts and replies are kept if the site says so, and removed later.
     */
    public function test_log_content(): void {
        global $DB;
        set_config('logprompts', 1, 'tool_aibridge');
        set_config('logresponses', 1, 'tool_aibridge');
        set_config('contentretention', 30, 'tool_aibridge');
        set_config('logretention', 365, 'tool_aibridge');
        $this->get_generator()->create_provider();
        \curl::mock_response(self::CHAT_REPLY);
        $response = manager::process($this->text_action());
        $log = $DB->get_record(logger::TABLE, ['id' => $response->get_logid()]);
        $this->assertSame("Be brief.\n\nSay hello", $log->prompt);
        $this->assertSame('Hello there', $log->response);

        logger::cleanup(time() + 31 * DAYSECS);
        $log = $DB->get_record(logger::TABLE, ['id' => $response->get_logid()]);
        $this->assertNull($log->prompt);
        $this->assertNull($log->response);

        logger::cleanup(time() + 366 * DAYSECS);
        $this->assertFalse($DB->record_exists(logger::TABLE, ['id' => $response->get_logid()]));
    }

    /**
     * A {{SYSTEM}} token gets the system instructions; without one, they come before the prompt.
     */
    public function test_system_token(): void {
        $provider = $this->get_generator()->create_provider();
        $tokens = $this->text_action()->get_tokens($provider);
        $this->assertSame("Be brief.\n\nSay hello", $tokens['PROMPT']);
        $this->assertArrayNotHasKey('SYSTEM', $tokens);

        $template = '{"system": "{{SYSTEM}}", "messages": [{"role": "user", "content": "{{PROMPT}}"}]}';
        $provider = provider::save((object) ['id' => $provider->get_id(), 'requesttemplate' => $template]);
        $tokens = $this->text_action()->get_tokens($provider);
        $this->assertSame('Say hello', $tokens['PROMPT']);
        $this->assertSame('Be brief.', $tokens['SYSTEM']);
    }

    /**
     * Speech is generated, and the audio type is recognised.
     */
    public function test_generate_speech(): void {
        $this->get_generator()->create_provider(['capability' => 'speech']);
        $action = new generate_speech($this->context->id, $this->user->id, 'Hello', 'nova', 'en-GB');
        \curl::mock_response('ID3' . str_repeat("\0", 50));
        $response = manager::process($action);
        $this->assertTrue($response->get_success(), $response->get_error());
        $this->assertSame('audio/mpeg', $response->get_mimetype());
        $this->assertSame('mp3', $response->get_extension());

        // The audio can be saved as a file.
        $file = $response->save_audio(['contextid' => $this->context->id, 'component' => 'mod_test',
                'filearea' => 'audio', 'itemid' => 0, 'filename' => 'hello.txt']);
        $this->assertSame('hello.mp3', $file->get_filename());

        // The voice and language are tokens.
        $provider = provider::get($response->get_providerid());
        $tokens = $action->get_tokens($provider);
        $this->assertSame('nova', $tokens['VOICE']);
        $this->assertSame('en-GB', $tokens['LANGUAGE']);

        // An empty voice uses the provider's default.
        $action = new generate_speech($this->context->id, $this->user->id, 'Hello');
        $this->assertArrayNotHasKey('VOICE', $action->get_tokens($provider));
        $this->assertSame('alloy', $provider->get_token_defaults()['VOICE']);
    }

    /**
     * Speech in a JSON reply, as base64 PCM, is turned into a WAV file.
     */
    public function test_generate_speech_json(): void {
        $this->get_generator()->create_provider(['preset' => 'geminitts', 'capability' => 'speech']);
        $reply = ['candidates' => [['content' => ['parts' => [['inlineData' => [
            'mimeType' => 'audio/L16;codec=pcm;rate=24000',
            'data' => base64_encode(str_repeat("\0\0", 100)),
        ]]]]]]];
        \curl::mock_response(json_encode($reply));
        $response = manager::process(new generate_speech($this->context->id, $this->user->id, 'Hello'));
        $this->assertTrue($response->get_success(), $response->get_error());
        $this->assertSame('wav', $response->get_extension());
    }

    /**
     * Images are generated, in the right size, and can be saved as files.
     */
    public function test_generate_image(): void {
        $png = "\x89PNG\r\n\x1a\n" . str_repeat("\0", 20);
        $provider = $this->get_generator()->create_provider(['capability' => 'image']);
        $action = new generate_image($this->context->id, $this->user->id, 'A swan by a pond.', 'landscape', 'hd');
        $tokens = $action->get_tokens($provider);
        $this->assertSame('1536x1024', $tokens['SIZE']);
        $this->assertSame('16:9', $tokens['RATIO']);
        $this->assertSame('high', $tokens['QUALITY']);

        \curl::mock_response(json_encode(['data' => [['b64_json' => base64_encode($png)]]]));
        $response = manager::process($action);
        $this->assertTrue($response->get_success(), $response->get_error());
        $this->assertSame('image/png', $response->get_mimetype());
        $this->assertSame($png, $response->get_image());
        $file = $response->save_image(['contextid' => $this->context->id, 'component' => 'mod_test',
            'filearea' => 'image', 'itemid' => 0, 'filename' => 'swan']);
        $this->assertSame('swan.png', $file->get_filename());

        // A text provider cannot make images.
        $this->assertSame(['image'], $action->get_capabilities());
    }

    /**
     * DALL-E 3 sizes and its rewritten prompt; Imagen ratios; and images given as URLs.
     */
    public function test_generate_image_presets(): void {
        $jpeg = "\xFF\xD8\xFF\xE0" . str_repeat("\0", 20);
        $dalle = $this->get_generator()->create_provider(['preset' => 'dalle3', 'capability' => 'image']);
        $action = new generate_image($this->context->id, $this->user->id, 'A swan.', 'portrait');
        $this->assertSame('1024x1792', $action->get_tokens($dalle)['SIZE']);
        $this->assertSame('natural', $dalle->get_token_defaults()['STYLE']);
        \curl::mock_response(json_encode(['data' => [['b64_json' => base64_encode($jpeg), 'revised_prompt' => 'A white swan.']]]));
        $response = manager::process($action, $dalle->get_id());
        $this->assertTrue($response->get_success(), $response->get_error());
        $this->assertSame('jpg', $response->get_extension());
        $this->assertSame('A white swan.', $response->get_content());

        $imagen = $this->get_generator()->create_provider(['preset' => 'imagen', 'capability' => 'image']);
        $this->assertSame('9:16', $action->get_tokens($imagen)['RATIO']);

        // A reply with a URL: the image is downloaded. Mocked replies are used last first.
        \curl::mock_response($jpeg);
        \curl::mock_response(json_encode(['data' => [['b64_json' => 'https://images.example.com/swan.jpg']]]));
        $response = manager::process($action, $dalle->get_id());
        $this->assertTrue($response->get_success(), $response->get_error());
        $this->assertSame($jpeg, $response->get_image());

        // A reply that is not an image.
        \curl::mock_response(json_encode(['data' => [['b64_json' => base64_encode('<html>Error</html>')]]]));
        $this->assertSame('notimage', manager::process($action, $dalle->get_id())->get_errorcode());
    }

    /**
     * If one provider fails, the next is tried.
     */
    public function test_fallback(): void {
        global $DB;
        $this->get_generator()->create_provider(['name' => 'Broken', 'returnpath' => 'no,such,path', 'sortorder' => 1]);
        $this->get_generator()->create_provider(['name' => 'Working', 'sortorder' => 2]);
        \curl::mock_response(self::CHAT_REPLY);
        \curl::mock_response(self::CHAT_REPLY);

        $response = manager::process($this->text_action());
        $this->assertTrue($response->get_success());
        $this->assertSame('Working', $response->get_providername());
        $this->assertSame(2, $DB->count_records(logger::TABLE));
        $this->assertSame(1, $DB->count_records(logger::TABLE, ['success' => 0, 'errorcode' => 'replynotext']));
    }

    /**
     * API keys are not in error messages or the log.
     */
    public function test_error_hides_key(): void {
        global $DB;
        set_config('curlsecurityblockedhosts', 'blocked.test');
        $this->get_generator()->create_provider(['apikey' => 'sk-very-secret',
                'url' => 'https://blocked.test/v1?key={{APIKEY}}']);
        $response = manager::process($this->text_action());
        // Moodle 4.x and later report the blocked URL, so keys belong in headers, not URLs.
        $this->resetDebugging();
        $this->assertFalse($response->get_success());
        $this->assertStringNotContainsString('sk-very-secret', $response->get_error());
        $log = $DB->get_record(logger::TABLE, []);
        $this->assertStringNotContainsString('sk-very-secret', $log->error);
    }

    /**
     * Users must accept the policy first, if the site says so.
     */
    public function test_policy(): void {
        set_config('requirepolicy', 1, 'tool_aibridge');
        $this->get_generator()->create_provider();
        $response = manager::process($this->text_action());
        $this->assertSame('policynotaccepted', $response->get_errorcode());
        $this->assertNotEmpty($response->get_error());

        policy::accept($this->user->id, $this->context->id);
        \curl::mock_response(self::CHAT_REPLY);
        $this->assertTrue(manager::process($this->text_action())->get_success());

        policy::reset();
        $this->assertFalse(policy::has_accepted($this->user->id));
        $this->assertStringContainsString('/admin/tool/aibridge/policy.php', policy::get_url($this->context)->out());

        $notices = policy::get_data_notices($this->context, $this->user->id);
        $this->assertCount(1, $notices);
        $this->assertStringContainsString('api.openai.com', reset($notices));
    }

    /**
     * Rate limits stop requests: for the site, for each user, and for each user of a shared provider.
     */
    public function test_rate_limits(): void {
        $provider = $this->get_generator()->create_provider(['userratelimit' => 1]);
        \curl::mock_response(self::CHAT_REPLY);
        $this->assertTrue(manager::process($this->text_action())->get_success());
        $this->assertSame('providerratelimit', manager::process($this->text_action())->get_errorcode());

        // The owner has no limit on their own provider.
        $this->assertTrue(rate_limiter::check_provider($provider, (int) $provider->get_record()->ownerid));

        set_config('userratelimit', 1, 'tool_aibridge');
        $this->assertSame('userratelimit', manager::process($this->text_action())->get_errorcode());
        set_config('userratelimit', 0, 'tool_aibridge');
        set_config('siteratelimit', 1, 'tool_aibridge');
        $this->assertSame('siteratelimit', manager::process($this->text_action())->get_errorcode());
    }

    /**
     * Nothing is sent when the bridge is off, when there are no providers, or when the action is not valid.
     */
    public function test_not_sent(): void {
        $this->assertSame('noproviders', manager::process($this->text_action())->get_errorcode());
        $this->assertFalse(manager::is_available($this->text_action()));

        $this->get_generator()->create_provider();
        $this->assertTrue(manager::is_available($this->text_action()));
        $this->assertSame('noprompt', manager::process($this->text_action(' '))->get_errorcode());

        // A text provider cannot speak.
        $action = new generate_speech($this->context->id, $this->user->id, 'Hello');
        $this->assertSame('noproviders', manager::process($action)->get_errorcode());

        set_config('allowexternal', 0, 'tool_aibridge');
        $this->assertFalse(manager::is_available($this->text_action()));

        set_config('enabled', 0, 'tool_aibridge');
        $this->assertSame('disabled', manager::process($this->text_action())->get_errorcode());
    }

    /**
     * One provider can be chosen.
     */
    public function test_choose_provider(): void {
        $this->get_generator()->create_provider(['name' => 'First']);
        $second = $this->get_generator()->create_provider(['name' => 'Second']);
        \curl::mock_response(self::CHAT_REPLY);
        $response = manager::process($this->text_action(), $second->get_id());
        $this->assertSame('Second', $response->get_providername());
    }

    /**

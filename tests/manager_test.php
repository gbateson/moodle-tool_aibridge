     */
    public function test_test(): void {
        set_config('requirepolicy', 1, 'tool_aibridge');
        $provider = $this->get_generator()->create_provider();
        \curl::mock_response(self::CHAT_REPLY);
        $response = manager::test($provider, $this->context, get_admin()->id);
        $this->assertTrue($response->get_success());
    }

    /**
     * The request template is checked before it is sent.
     */
    public function test_template_check(): void {
        $this->assertTrue(form\provider_form::is_json_template('{"a": "{{PROMPT}}", "n": {{MAXTOKENS}}}'));
        $this->assertTrue(form\provider_form::is_json_template('{"parts": [{{FILE_PARTS}} {"text": "{{PROMPT}}"}]}'));
        $this->assertFalse(form\provider_form::is_json_template('{"a": {{PROMPT}}'));
        foreach (presets::get_presets() as $name => $preset) {
            $this->assertTrue(form\provider_form::is_json_template($preset['requesttemplate']), $name);
        }
    }

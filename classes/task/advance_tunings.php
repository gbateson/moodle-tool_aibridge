class advance_tunings extends \core\task\scheduled_task {
    /**
     * Get the name of the task.
     *
     * @return string
     */
    public function get_name() {
        return get_string('taskadvancetunings', 'tool_aibridge');
    }

    /**
     * Do the task.
     */
    public function execute() {
        $count = \tool_aibridge\tuning::advance_all();
        if ($count) {
            mtrace("Checked $count fine-tuning job(s).");
        }
    }
}
